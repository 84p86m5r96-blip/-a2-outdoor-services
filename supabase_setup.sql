-- A2 Outdoor Services secure owner setup
-- Run this in Supabase SQL Editor after creating your project.
-- Create your owner account in Authentication > Users first.

create table if not exists public.owner_access (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.owner_access enable row level security;

create policy "Owners can read their own access row"
on public.owner_access
for select
to authenticated
using (auth.uid() = user_id);

