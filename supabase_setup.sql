-- Example protected bookings table. Add only the columns you actually need.
create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  service text not null,
  booking_date timestamptz not null,
  status text not null default 'pending',
  created_at timestamptz not null default now()
);

alter table public.bookings enable row level security;

create policy "Only approved owner can read bookings"
on public.bookings
for select
to authenticated
using (exists (select 1 from public.owner_access oa where oa.user_id = auth.uid()));

create policy "Only approved owner can change bookings"
on public.bookings
for all
to authenticated
using (exists (select 1 from public.owner_access oa where oa.user_id = auth.uid()))
with check (exists (select 1 from public.owner_access oa where oa.user_id = auth.uid()));
